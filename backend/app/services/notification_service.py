"""
Sentinel SOS - Notification Service.

Orchestrates multi-channel emergency alerts (SMS, FCM Push, Email)
and records delivery attempts for auditing.
"""

from datetime import datetime, timezone
import uuid
from typing import Any, Dict, List, Optional
from app.core.config import settings
from app.core.logging import logger
from app.db.mongodb import get_mongo_db
from app.integrations.messaging.email import email_client
from app.integrations.messaging.push import push_client

_FALLBACK_NOTIFICATION_LOGS: List[Dict[str, Any]] = []


class NotificationService:
    def __init__(self):
        self.db = get_mongo_db()

    def send_sos_alert(
        self,
        incident_id: str,
        recipient_phone: str,
        citizen_name: str,
        location_url: str,
    ) -> Dict[str, Any]:
        """Dispatches an emergency alert SMS/notification to a trusted contact."""
        attempt_id = f"notif_{uuid.uuid4().hex[:10]}"
        now = datetime.now(timezone.utc)

        message_body = (
            f"EMERGENCY ALERT: {citizen_name} has triggered an SOS! "
            f"Track live incident location: {location_url}"
        )

        status = "DELIVERED" if settings.SMS_PROVIDER == "mock" else "SUBMITTED"
        log_entry = {
            "attempt_id": attempt_id,
            "incident_id": incident_id,
            "channel": "sms",
            "provider": settings.SMS_PROVIDER,
            "destination": recipient_phone,
            "body": message_body,
            "status": status,
            "created_at": now,
        }

        if self.db is not None:
            try:
                self.db["notification_attempts"].insert_one(log_entry.copy())
            except Exception as e:
                logger.error(f"Failed to record notification log in MongoDB: {e}")
        else:
            _FALLBACK_NOTIFICATION_LOGS.append(log_entry.copy())

        logger.info(f"Notification [{status}] to {recipient_phone} for incident {incident_id}")
        return log_entry

    async def send_sos_email(
        self,
        incident_id: str,
        recipient_email: str,
        citizen_name: str,
        location_url: str,
        emergency_type: str = "EMERGENCY",
    ) -> Dict[str, Any]:
        """Dispatches an emergency alert Email via Resend to a trusted contact or responder."""
        attempt_id = f"notif_email_{uuid.uuid4().hex[:10]}"
        now = datetime.now(timezone.utc)

        subject = f"🚨 URGENT: Emergency SOS Alert for {citizen_name}"
        html_content = f"""
        <div style="font-family: Arial, sans-serif; max-width: 600px; margin: 0 auto; padding: 20px; border: 1px solid #e2e8f0; border-radius: 8px;">
            <h2 style="color: #dc2626; margin-top: 0;">🚨 Sentinel SOS Emergency Alert</h2>
            <p style="font-size: 16px;"><strong>{citizen_name}</strong> has triggered an emergency SOS alert.</p>
            <div style="background-color: #fef2f2; border-left: 4px solid #ef4444; padding: 12px; margin: 16px 0;">
                <p style="margin: 0; color: #991b1b;"><strong>Incident ID:</strong> {incident_id}</p>
                <p style="margin: 4px 0 0; color: #991b1b;"><strong>Emergency Type:</strong> {emergency_type}</p>
            </div>
            <p>
                <a href="{location_url}" style="display: inline-block; background-color: #dc2626; color: white; padding: 12px 24px; text-decoration: none; border-radius: 6px; font-weight: bold;">
                    Track Live Location
                </a>
            </p>
            <hr style="border: none; border-top: 1px solid #e2e8f0; margin: 20px 0;" />
            <p style="font-size: 12px; color: #64748b;">This is an automated safety alert generated by the Sentinel SOS Emergency Response System.</p>
        </div>
        """

        result = await email_client.send_email(
            to_email=recipient_email,
            subject=subject,
            html_content=html_content,
        )

        log_entry = {
            "attempt_id": attempt_id,
            "incident_id": incident_id,
            "channel": "email",
            "provider": result.get("provider", "resend"),
            "destination": recipient_email,
            "status": result.get("status", "SUBMITTED"),
            "details": result,
            "created_at": now,
        }

        if self.db is not None:
            try:
                self.db["notification_attempts"].insert_one(log_entry.copy())
            except Exception as e:
                logger.error(f"Failed to record email notification log in MongoDB: {e}")
        else:
            _FALLBACK_NOTIFICATION_LOGS.append(log_entry.copy())

        return log_entry

    async def send_sos_push(
        self,
        incident_id: str,
        fcm_token: str,
        title: str,
        body: str,
        data: Optional[Dict[str, str]] = None,
    ) -> Dict[str, Any]:
        """Dispatches an emergency push notification via Firebase Cloud Messaging."""
        attempt_id = f"notif_push_{uuid.uuid4().hex[:10]}"
        now = datetime.now(timezone.utc)

        result = await push_client.send_push(
            target_token=fcm_token,
            title=title,
            body=body,
            data=data,
        )

        log_entry = {
            "attempt_id": attempt_id,
            "incident_id": incident_id,
            "channel": "push",
            "provider": "fcm",
            "destination": fcm_token[:20] + "...",
            "status": result.get("status", "SUBMITTED"),
            "details": result,
            "created_at": now,
        }

        if self.db is not None:
            try:
                self.db["notification_attempts"].insert_one(log_entry.copy())
            except Exception as e:
                logger.error(f"Failed to record push notification log in MongoDB: {e}")
        else:
            _FALLBACK_NOTIFICATION_LOGS.append(log_entry.copy())

        return log_entry

